// ===== มหาโบตะ (โหราศาสตร์พม่า) =====
// สูตร: เรือนเกิด = (ปีพม่า − เลขวันพม่า) mod 7 · เลขวัน: เสาร์ 0 อาทิตย์ 1 จันทร์ 2 อังคาร 3 พุธ 4 พฤหัส 5 ศุกร์ 6
//   ผล 0 = บินกะ · 1 = อะตุน · 2 = ยาซา · 3 = อธิปติ · 4 = มรณะ · 5 = ไตก์ · 6 = ปุติ
//   (อ้างอิงสูตรของ Yan Naing Aye ผู้เขียนอัลกอริทึมปฏิทินพม่า cool-emerald.blogspot.com)
// ปีพม่า ≈ ปี ค.ศ. − 639 ถ้าเกิดก่อน 16 เม.ย. (ก่อนสงกรานต์พม่า) · − 638 ถ้าเกิดตั้งแต่ 16 เม.ย.
// วันพุธหลังเที่ยงวันนับเป็นราหู (ระบบ 8 ดาวของพม่า) · วันพม่าเปลี่ยนตอนเที่ยงคืน
// ⚠️ ความหมายเรือนเป็นร่างจากความหมายที่นิยมทั่วไป ควรให้ผู้รู้โหราศาสตร์พม่าตรวจก่อนใช้จริง

import { kbRows, kbReviewed } from './kb.js';
const PLANET = ['เสาร์', 'อาทิตย์', 'จันทร์', 'อังคาร', 'พุธ', 'พฤหัสบดี', 'ศุกร์'];
const ANIMAL = ['นาค', 'ครุฑ', 'เสือ', 'สิงห์', 'ช้างมีงา', 'หนู', 'หนูตะเภา']; // สัตว์ประจำวันพม่า (เสาร์ → ศุกร์) · พุธบ่ายเป็นช้างไม่มีงา

// y m d = วันเกิดตามปฏิทินสากล · hour = ชั่วโมงเกิด (ไม่มีก็ได้)
export function mahabote(y, m, d, hour) {
  const my = y - (m < 4 || (m === 4 && d < 16) ? 639 : 638);
  const jsDay = new Date(Date.UTC(y, m - 1, d)).getUTCDay(); // 0 = อาทิตย์
  const wd = (jsDay + 1) % 7; // 0 = เสาร์ แบบพม่า
  const house = (((my - wd) % 7) + 7) % 7;
  const rahu = wd === 4 && Number.isFinite(hour) && hour >= 12;
  const notes = [];
  if (m === 4 && d >= 13 && d <= 17) notes.push('เกิดช่วงสงกรานต์พม่า ปีพม่าอาจคลาด 1 ปี ควรตรวจกับปฏิทินพม่า');
  if (wd === 4 && !Number.isFinite(hour)) notes.push('เกิดวันพุธแต่ไม่ทราบเวลา (พุธบ่ายนับเป็นราหู)');
  return {
    myanmarYear: my, remainder: ((my % 7) + 7) % 7,
    planet: rahu ? 'ราหู' : PLANET[wd], animal: rahu ? 'ช้างไม่มีงา' : ANIMAL[wd],
    house: kbRows('mahabote')[house], notes,
  };
}

export function mahaboteText(r) {
  if (!r) return '';
  return `มหาโบตะ (พม่า): ปีพม่า ${r.myanmarYear} · ดาววันเกิด ${r.planet} (สัตว์ประจำวัน ${r.animal}) · เกิดในเรือน${r.house.th} — ${r.house.mean}${kbReviewed('mahabote') ? '' : ' (ความหมายเรือนเป็นร่าง)'}${r.notes.length ? ` · ${r.notes.join(' · ')}` : ''}`;
}
